    def parse_call_command
      trace
      call = Ast::CallCommand.new(read)
      call.references = parse_references
#     readkinds(:REF, :IDENT).each { call.references << Ast::Reference.new(_1) }
      call
    end

    def parse_if
      trace
      if_ = Ast::If.new(peek)
      loop do
        if_then = Ast::IfThen.new(read)
        if_then.expr = parse_expr
        if_then.then_ = parse_block
        if_.if_thens << if_then
        break if peek.kind != :ELSIF
      end
      if peek.kind == :ELSE
        read
        if_.else_ = parse_block
      end
      readkind(:END)
      if_
    end

    def parse_case
      trace
      case_ = Ast::Case.new(read)
      case_.expr = parse_expr
      while peek.kind == :WHEN
        when_ = Ast::When.new(read)
        when_.exprs = parse_when_exprs
        when_.then_ = parse_block
        case_.whens << when_
      end
      !case_.whens.empty? or unexpected_token_error peek, "'when'"
      if peek.kind == :ELSE
        read
        case_.else_ = parse_block
      end
      readkind(:END)
      case_
    end

    # Parse a comma-separated list of when-expr. A when-expr is an optional
    # operator followed by a value
    def parse_when_exprs
      trace
      exprs = []
      while true
        token = peek.is_oper? ? read : peek
        when_expr = Ast::WhenExpr.new(token)
        when_expr.rexpr = parse_value
        exprs << when_expr
        break if !readkind?(:COMMA)
      end
      exprs
    end

