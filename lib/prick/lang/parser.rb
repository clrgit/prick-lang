
module Prick::Lang
  class Parser < CompilerProcess
    using String::Text

    CONSTANTS = [:ENV, :CMD, :USER, :VAR, :VERSION, :SCHEMA, :OBJECT, :RESOURCE]
    COMMANDS = [:EXEC, :EVAL, :RUBY, :SQL, :CALL, :ECHO]

    # Map from operator token kind to hash of
    #
    #   {
    #     prior: Integer        # Priority,
    #     assoc: :left|:right   # Associtivity
    #     arity: Integer        # Arity
    #     value: Boolean        # True if the operator accepts a value rval
    #     list: Boolean         # True if the operator accepts a list rval
    #   }
    #
    OPERATORS = {
      OROR: [0, :left, 2, true, false],
      ANDAND: [1, :left, 2, true, false],
      LT: [2, :left, 2, true, false],
      LE: [2, :left, 2, true, false],
      EQ: [2, :left, 2, true, false],
      NE: [2, :left, 2, true, false],
      GE: [2, :left, 2, true, false],
      GT: [2, :left, 2, true, false],
      TIGT: [2, :left, 2, true, false],
      IN: [3, :left, 2, false, true],
      PCT: [3, :left, 2, true, true], # TODO Special case - takes both an array and a value
      NOT: [3, :right, 1, true, false],
      TI: [4, :right, 1, true, false],
      QUEST: [5, :left, 1, true, false],
    }.map { |k,v| [k, { prior: v[0], assoc: v[1], arity: v[2], value: v[3], list: v[4] } ] }.to_h

    # Operators for comparing versions
    VERSION_OPERATORS = Set[:LT, :LE, :EQ, :NE, :GE, :GT, :TIGT]

    # The current tokenizer. Maintained by #push_tokenizer and #pop_tokenizer.
    # Initially nil
    attr_reader :tokenizer

    # The starting file name. Initialized by #parse
    def file = @file

    # The AST generated by #parse
    attr_reader :ast

    def token = @tokenizer.token
    def peek_token = @tokenizer.peek_token

    def initialize
      @tokenizers = [] # Stack of tokenizers
      @ast = nil
    end

    def parse(file, lines = nil)
      constrain file, String
      @file = file
      begin
        push_tokenizer Tokenizer.new(file, lines)
        @ast = parse_program
        read(eof:false)
        if !@tokenizer.eof?
          unexpected_token_error token, "end of file"
        end
      ensure
        pop_tokenizer
      end
      @ast
    end

    def inspect = "<Parser: #{file}>"

  private
    def push_tokenizer(tokenizer) = @tokenizers.push (@tokenizer = tokenizer)
    def pop_tokenizer() = @tokenizers.tap { @tokenizer = _1[-2] }.pop

    def parse_program
      token = ProgramToken.new(self.file, 1, 1)
      file = Ast::File.new(token, @tokenizer.dir)
      @ast = Ast::Program.new(file)
      compiler.sources << @ast
      @ast.block = parse_block(check: false)
      @ast
    end

    def parse_stmt
      case peek&.kind
        when :SCHEMA; parse_decl(Ast::Schema, read)
        when :PROCEDURE; parse_decl(Ast::Procedure, read)
        when :OPTIONS; parse_options
        when :PROVIDE; parse_provide
        when :REQUIRE; parse_require
        when :META; parse_meta
        when :IF; parse_if
        when :CASE; parse_case
        when *Token::PHASES; parse_decl(Ast::Phase, peek)
        when :EXEC, :EVAL, :ECHO, :SQL; parse_command
        when :RUBY; not_implemented_error "'ruby' command"
        when :CALL; parse_call_command
        when :CHECK; parse_check_command
        when :FILE; parse_file
        when :DIR; parse_dir
      else
        return nil
      end
    end

    def parse_stmts(check: true)
      stmts = []
      while stmt = parse_stmt
        stmts << stmt
      end
      stmts
    end

    #
    # S E C T I O N S
    #

    # Parse a statement block (a list of statements). Checks for non-empty when
    # :check is true (the default)
    #
    def parse_block(token = nil, check: true)
      block = Ast::Block.new(token) # Note that token may be nil, it is assigned later if so
      block.stmts = parse_stmts
      if block.stmts.empty? && !check
        unexpected_token_error token, "block" if check
      else
        block.token ||= block.start_token # Default token to start token
      end
      block
    end

    # Schema, phase, or function declarations. Uses that they have the same
    # parts
    def parse_decl(klass, token)
      decl = klass.new(token)
      decl.ident = parse_name
      token = readkind(:BRACE_BEGIN)
      decl.block = parse_block(token, check: false)
      decl.block.stop_token = readkind(:BRACE_END)
      decl
    end

    #
    # D E P E N D E N C I E S
    #

    def parse_provide
      provide = Ast::Provide.new(read)
      provide.ident = parse_name
      provide
    end

    def parse_require
      require_ = Ast::Require.new(read)
      require_.references = parse_references
      require_
    end

    def parse_meta

      make = Ast::Meta.new(read)
      make.tables = parse_references
      make
    end

    #
    # C O M M A N D S
    #

    def parse_command
      token = read
      if token.kind == :SQL
        command = Ast::SqlCommand.new(token)
      else
        command = Ast::ExternalCommand.new(token, @tokenizer.dir)
      end
      if peek(eol: true).kind == :PIPE
        read
        limit = @tokenizer.line.indentation
        @tokenizer.readeol
        command.source = readtext(limit)&.text
      else
        command.source = readline&.text
      end or unexpected_token_error peek, "command"
      command
    end

    def parse_file
      if peek.extname == Token::PRICK_EXT
        parse_prick_file
      else
        command = Ast::FileCommand.new peek
        command.file = Ast::File.new(read, @tokenizer.dir)
        command
      end
    end

    def parse_dir
      parse_prick_file File.join(peek_token.path, Compiler::DEFAULT_SOURCE_FILE)
    end

    def parse_prick_file(path = nil)
      read
      path ||= token.path
      File.readable?(path) or error token, "Can't read #{path}"

      if compiler.sources.include? path
        Ast::Nop.new(token)
      else
        source = Ast::Source.new token
        source.file = Ast::File.new(token, path, @tokenizer.dir)
        compiler.sources << source
        begin
          push_tokenizer Tokenizer.new path
          Dir.chdir(File.dirname(path)) {
            source.block = parse_block(nil, check: false)
          }
        ensure
          pop_tokenizer
        end
        source
      end
    end

    def parse_call_command
      call = Ast::CallCommand.new(read)
      call.references = parse_references
#     readkinds(:REF, :IDENT).each { call.references << Ast::Reference.new(_1) }
      call
    end

    def realpath(path)
      path[0] == "/" ? path : File.join(@tokenizer.dir, path)
    end

    #
    # C O N T R O L   S T A T E M E N T S
    #

    def parse_if
      if_ = Ast::If.new(peek)
      loop do
        if_then = Ast::IfThen.new(read)
        if_then.expr = parse_expr
        if_then.then_ = parse_block
        if_.if_thens << if_then
        break if peek.kind != :ELSIF
      end
      if peek.kind == :ELSE
        read
        if_.else_ = parse_block
      end
      readkind(:END)
      if_
    end

    def parse_case
      case_ = Ast::Case.new(read)
      case_.expr = parse_expr
      while peek.kind == :WHEN
        when_ = Ast::When.new(read)
        when_.exprs = parse_when_exprs
        when_.then_ = parse_block
        case_.whens << when_
      end
      !case_.whens.empty? or unexpected_token_error peek, "'when'"
      if peek.kind == :ELSE
        read
        case_.else_ = parse_block
      end
      readkind(:END)
      case_
    end

    # Parse a comma-separated list of when-expr. A when-expr is an optional
    # operator followed by a value
    def parse_when_exprs
      exprs = []
      while true
        token = peek.is_oper? ? read : peek
        when_expr = Ast::WhenExpr.new(token)
        when_expr.rexpr = parse_value
        exprs << when_expr
        break if !readkind?(:COMMA)
      end
      exprs
    end

    def parse_ruby
      not_implemented_error "#parse_ruby"
    end

    def parse_check_command
      check = Ast::Check.new(read)

      readrest { readpath(eol: true) }.each { |token|
        oper = Ast::UnaryExpr.new(check.token)
        oper.expr = Ast::Path.new(token)
        check.exprs << oper
      }

      case t = peek(eol: true).kind
        when :PIPE
          pipe = read(eol: true)
          check.then_ = Ast::Block.new(pipe)
          command = Ast::ExternalCommand.new(pipe, :EXEC, @tokenizer.dir)
          check.then_.stmts << command
          limit = @tokenizer.line.indentation
          @tokenizer.readeol
          command.source = readtext(limit)&.text
        when :EOL
          read(eol: true)
          check.then_ = parse_block
          readkind(:END)
        else
          unexpected_token_error peek(eol: true), "block or exec expression"
      end
      check
    end

    #
    # E X P R E S S I O N S
    #

    # Parse a value and return it. Called from the shunter
    #
    # If token is a (qualified) identfier and the next token is '?', a
    # Ast::Reference token is returned
    def parse_value
      token = read(eol: true)
      case token.kind
        when *Token::REFS; peek(eol: true).kind == :QUEST ? Ast::Reference.new(token) : Ast::Word.new(token)
        when :VAR; Ast::Var.new(token)
        when :VER; Ast::Ver.new(token)
        when :TRUE, :FALSE; Ast::Bool.new(token)
        when :FILE, :DIR; Ast::File.new(token, @tokenizer.dir)
        when :PATH; Ast::Path.new(token)
        when :EOL; raise "FIXME what when?"
      else
        raise InternalError
      end
    end

    # Parse an expression. It uses the shunter to compile the source into
    # reverse polish notation that is then converted into an Ast::Expr
    def parse_expr
      stack = ExprStack.new # [Ast::Expr]
      shunt_exprs.each { |token|
        case token
          when ParenToken
            e = Ast::ParenExpr.new(token)
            e.expr = stack.pop
            stack.push e
          when ListToken
            e = Ast::ListExpr.new(token)
            e.elems = stack.pop(token.size)
            stack.push e
          else
            if operator = OPERATORS[token.kind]
              case operator[:arity]
                when 1
                  e = Ast::UnaryExpr.new(token)
                  e.expr = stack.pop
                  stack.push e
                when 2
                  e = Ast::BinaryExpr.new(token)
                  if operator[:list]
                    if stack.top.is_a? Ast::ParenExpr
                      e.rexpr = Ast::ListExpr.new(token)
                      e.rexpr.elems = [stack.pop]
                    elsif stack.top.is_a? Ast::ListExpr
                      e.rexpr = stack.pop
                    elsif operator[:value] # Handle value argument to list operator
                      list = Ast::ListExpr.new(token)
                      list.elems = [stack.pop]
                      e.rexpr = list
                    else
                      unexpected_token_error peek, "list expression"
                    end
                  else
                    e.rexpr = stack.pop
                  end
                  e.lexpr = stack.pop
                  stack.push e
                when nil
              end
            else
              stack.push token
#             stack.size == 1 or unexpected_token_error peek, "expression"
            end
        end
      }
      r = stack.pop
      stack.empty? or unexpected_token_error peek, "expression"
      r
    end

    #
    # S H U N T I N G
    #

    class ExprStack < Array
      alias :_pop :pop

      def pop(*args)
        while self.top.is_a? Ast::ParenExpr
          self.push self._pop.expr
        end
        super(*args)
      end
    end

    # Returns a reversed Polish notation list of tokens or Ast::Value objects
    def shunt_exprs
      stack = [] # [Token]. Operator stack
      output = [] # [Token]

      paren_level = 0 # Tracks parenthesis levels
      accept_eol = true # Signals that the expression continues on the next line
      last_was_bin_oper = false # Signals that the last token was a binary operator

      while token = @tokenizer.peek(eol: true)
        this_is_bin_oper = false
        case token.kind
          when :EOL
            break if paren_level == 0 && !accept_eol
            read(eol: true)

          when :PAREN_BEGIN
            read(eol: true)
            if peek(eol: false)&.kind == :PAREN_END
              read(eol: true)
              output << ListToken.new(token, 0)
              accept_eol = false
            else
              paren_level += 1
              stack.push(token)
            end

          when :PAREN_END
            paren_level -= 1
            read(eol: true)
            last_was_list = false # Don't output both PAREN and LIST
            while op = stack.pop
              if op.is_a?(Token) && op.kind == :PAREN_BEGIN
                output << ParenToken.new(op) if !last_was_list
                break
              elsif op.is_a? ListToken
                last_was_list = true
                op.size += 1
              end
              output << op
            end

          # A comma rewinds the stack like paren-end but leaves the paren-begin
          # token and push an element counter that is increment for each new
          # comma
          when :COMMA
            paren_level > 0 or error token, "Unexpected ','"
            read(eol: true)
            while op = stack.top
              if op.is_a?(Token) && op.kind == :PAREN_BEGIN # Only true on first comma
                stack.push ListToken.new(op)
                break
              elsif op.is_a? ListToken
                op.size += 1
                break
              end
              output << stack.pop
            end

          when *Token::VALUES
            accept_eol = false
            output << parse_value

          when *Token::OPERS
            accept_eol = !token.is_suffix_oper?
            oper = OPERATORS[token.kind] or raise ArgumentError, "Not a known operator '#{token.text}'"

            # Prevent double binary operators. Eg '3 = = 4'
            if oper[:arity] == 2
              !last_was_bin_oper or unexpected_token_error peek, "expression"
              this_is_bin_oper = true
            end

            read eol: true

            # Parse next token as a path if check operator
            if token.kind == :TI
              path = @tokenizer.readpath(eol: true) or unexpected_token_error token, "path"
              output << Ast::Path.new(path)
              accept_eol = false
            end

            # we use .is_a?(Token) because the stack also can contain Ast::Node objects
            while stack.top.is_a?(Token) && top = OPERATORS[stack.top&.kind]
              break if oper[:prior] > top[:prior]
              break if oper[:prior] == top[:prior] && oper[:assoc] == :right
              output << stack.pop
            end

            stack.push token

          else
            break
        end
        last_was_bin_oper = this_is_bin_oper
      end
      output + stack.reverse
    end

    #
    # S I M P L E   E L E M E N T S
    #

    def parse_ident?
      return nil if @tokenizer.eol?
      token = peek(eol: true)
      Token::IDENTS.include?(token&.kind) ? Ast::Ident.new(read(eol: true)) : nil
    end
    def parse_ident = Ast::Ident.new(readpred(:is_ident?, eol: true))
    def parse_idents? = readwhile? { parse_ident? }
    def parse_idents = check_expected("identifier", eol: true) { readwhile { parse_ident? } }

    # Single-component reference used in declarations. It parsed as a Reference object
    # because we later want to compute the uid
    def parse_name = Token::IDENTS.include?(peek&.kind) ? Ast::Reference.new(read) : nil
    def parse_name? = Ast::Reference.new(readpred :is_ident? )

    def parse_reference?() = Token::REFS.include?(peek&.kind) ? Ast::Reference.new(read) : nil
    def parse_reference() Ast::Reference.new(readpred :is_ref?) end
    def parse_references? = readwhile? { parse_reference? }
    def parse_references = check_expected("reference") { readwhile { parse_reference? } }

    # Parse a space-separated list of values. Values are IDENT, REF, or a version match
    def parse_list?
      case peek.kind
        when *Token::REFS
          Ast::Reference.new(read)
        when :VER # Default '=' operator
          tk = read
          oper = Token.new(tk.file, tk.lineno, tk.charno, "=", :EQ)
          match = Ast::VersionMatch.new(oper)
          match.version = Ast::Ver.new(tk)
          match
        when *VERSION_OPERATORS
          match = Ast::VersionMatch.new(read)
          match.version = Ast::Ver.new(readkind(:VER))
          match
      else
        nil
      end
    end

    #
    # T O K E N I Z E R  I N T E R F A C E
    #
    # Functions from tokenizer with error handling. They return tokens and not
    # Ast objects like the simple element functions above

    def peek(**opts) = @tokenizer.peek(**opts) or error(@tokenizer.error_token)
    def peek?(**opts) = @tokenizer.peek(**opts)

    def read(**opts) = @tokenizer.read(**opts) or error(@tokenizer.error_token)
    def read?(**opts) = @tokenizer.read(**opts)

    def readpath(**opts) = @tokenizer.readpath(**opts) or error(@tokenizer.error_token)
    def readpath?(**opts) = @tokenizer.readpath(**opts)
    def readpaths(**opts) = readwhile { readpath(**opts) }
    def readpaths?(**opts) = readwhile? { readpath?(**opts) }

    def readline(**opts) = @tokenizer.readline(**opts) or error(@tokenizer.error_token)
    def readline?(**opts) = @tokenizer.readline(**opts)

    def readtext(limit, **opts) = @tokenizer.readtext(limit, **opts) or error(@tokenizer.error_token)
    def readtext?(limit, **opts) = @tokenizer.readtext(limit, **opts)

    def readkind(*kinds, **opts) = readkind?(*kinds, **opts) or unexpected_token_error kinds
    def readkind?(*kinds, **opts) = kinds.include?(peek(**opts)&.kind) ? read(**opts) : nil
    def readkinds(*kinds, **opts) = [readkind(*kinds, **opts)] + readkinds?(kinds, **opts)
    def readkinds?(*kinds, **opts) = readwhile { readkind?(*kinds, **opts) } # Returns [] if not found

    def readpred(pred, **opts) = readpred?(pred, **opts) or unexpected_token_error kinds
    def readpred?(pred, **opts) = peek(**opts).kind.send(pred) ? read(**opts) : nil
    def readpreds(pred, **opts) = [readpred(pred, **opts)] + readpreds?(pred, **opts)
    def readpreds?(pred, **opts) = readwhile { readpred?(pred, **opts) } # Returns [] if not found

    # Return nil if empty
    def readwhile(&block) = (r = readwhile?(&block)).empty? ? nil : r

    # Return [] if empty
    def readwhile?(&block)
      a = []
      r = yield
      while r
        a << r
        r = yield
      end
      a
    end

    # Read rest of tokens in the current line. Does not consume the EOF token.
    # The block should call one of the #read* methods with eol: true
    def readrest(&block) = (r = readrest?(&block)).empty? ? nil : r

    def readrest?(&block)
      a = []
      while !@tokenizer.eol?
        token = block.call or return a
        a << token
      end
      a
    end

    #
    # E R R O R   H A N D L I N G
    #

    # :call-seq:
    #   unexpected_token_error(token = @tokenizer.error_token || @tokenizer.token, *words)
    #
    # Raise an error with the message format
    #
    #   Expected WORD, ..., or WORD, got WORD
    #
    # The error will be located at the given token (default @tokenizer #error or
    # #token). Note that it does not check for an error, it only displays it
    #
    # Some prettyfication is done on words
    #
    def unexpected_token_error(*args)
      token = args.first.is_a?(Token) ? args.shift : @tokenizer.error || @tokenizer.peek_error || @tokenizer.token or
          raise ArgumentError
      words = seq Array(args).flatten.map! { |w| w.is_a?(Symbol) ? Token::NAMES[w] : w }.compact
      source = token.is_a?(ErrorToken) ? token.text : sprintf(token.format, token.text)
      got = (source.empty? ? "" : ", got #{source}")
      message = "Expected #{words}#{got}"
      error token, message
    end

    def check_expected(words, eol: false, &block)
      token = peek(eol: eol) and token.kind != :EOL and r = yield(token) or unexpected_token_error token, words
      r
    end

    def not_implemented_error(*args)
      token = args.first.is_a?(Token) ? args.shift : @tokenizer.error || @tokenizer.peek_error || @tokenizer.token
      token or raise ArgumentError
      method_name = args.shift
      message = "#{method_name} is not implemented"
      error token, message
    end

    #
    # U T I L I T I E S
    #

    # English language sequence of words. Eg 'a, b, or c'
    def seq(words)
      words.map!(&:to_s)
      case words.size
        when 1; words.first
        when 2; words.join(" or ")
        else words[0..-2].join(", ") + ", or " + words.last
      end
    end
  end
