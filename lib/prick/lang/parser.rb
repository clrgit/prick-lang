
module Prick::Lang
  class Parser
    using String::Text
    include ErrorFunctions
    class ParserError < Prick::Lang::Error; end

    CONSTANTS = [:ENV, :CMD, :USER, :VERSION, :SCHEMA, :OBJECT, :RESOURCE]
    COMMANDS = [:EXEC, :EVAL, :RUBY, :SQL, :CALL]

    # Map from operator token kind to tuple of priority, associtivity (:left
    # or :right), and arity. Used by the shunter
    OPERATORS = {
      OROR: [0, :left, 2],
      ANDAND: [1, :left, 2],
      LT: [2, :left, 2],
      LE: [2, :left, 2],
      EQEQ: [2, :left, 2],
      NEQ: [2, :left, 2],
      GE: [2, :left, 2],
      GT: [2, :left, 2],
      EXCLAIM: [3, :right, 1]
    }.map { |k,v| [k, { prior: v[0], assoc: v[1], arity: v[2] } ] }.to_h

    # Operators for comparing versions
    VERSION_OPERATORS = Set[:LT, :LE, :EQEQ, :NEQ, :GE, :GT, :TIGT]

    attr_reader :tokenizer
    forward_to :tokenizer, :compiler
    forward_to :compiler, :file

    # The AST generated by #parse
    attr_reader :ast

    def initialize(tokenizer)
      @tokenizer = tokenizer
      @ast = nil
    end

    def parse = parse_program

    def inspect = "<Parser: #{file}>"

    def dump
      puts self.class
      indent { puts "file: #{file}" }
    end

  protected
    def parse_program
#     puts "#parse_program"
      @ast = Ast::Program.new(file)
      parse_block(@ast)
      @ast
    end

    def parse_stmt(parent)
#     puts "#parse_stmt"
      case peek.kind
        when :SCHEMA, :FUNCTION; parse_decl parent
        when :OPTIONS; parse_options parent
        when :PROVIDE; parse_provide parent
        when :REQUIRE; parse_require parent
        when :IF; parse_if parent
        when :CASE; parse_case parent
        when :INIT, :TERM, :META, :SEEDS, :AUTH; parse_phase parent
        when :EXEC, :EVAL, :SQL; parse_command parent
        when :CALL; parse_call parent
        when :RUBY; not_implemented_error "'ruby' command"
        when :FILE; parse_files parent
      else
        return nil
      end
    end


    # Parse a statement block (a list of statements). Checks for non-empty when
    # :check is true (the default)
    #
    def parse_block(parent, token = nil, check: true)
      check_expected "block" do
        block = Ast::Block.new(parent, token) # Note that token may be nil
        true until parse_stmt(block).nil?
        next nil if block.empty? && check
        block.token ||= block.start_token # Default token to start token
        block
      end
    end

    # Parse a block expression
    #
    #   { ... }
    #   FILE...
    #   COMMAND
    #
    def parse_block_argument(parent)
      check_expected %w(block command file) do |token|
        if token.kind == :BRACE_BEGIN
          block = parse_block(parent, read, check: false)
          block.stop_token = readkind(:BRACE_END)
        else
          block = Ast::Block.new(parent, token)
          case token.kind
            when :FILE; parse_files block
            when *COMMANDS; parse_command block
          else
            nil
          end
        end
        block
      end
    end

    def parse_call(parent)
      call = Ast::CallCommand.new(parent, read)
      readkinds(:REF, :IDENT).each { Ast::Reference.new(call, _1) }
      call
    end

    # Schema or function declaration
    def parse_decl(parent)
#     puts "parse_decl"
      decl = Ast::Decl.new(parent, read)
      decl.ident = parse_ident(decl)
      decl.block = parse_block_argument(decl)
      decl
    end

    def parse_provide(parent)
      provide = Ast::Provide.new(parent, read)
      parse_ident(provide)
      provide
    end

    def parse_require(parent)
      require_ = Ast::Require.new(parent, read)
      readkinds(:REF, :IDENT).each { Ast::Reference.new(require_, _1) }
      require_
    end

    # init, data, meta, etc. phases
    def parse_phase(parent)
#     puts "parse_phase"
      phase = Ast::Phase.new(parent, read)
      phase.block = parse_block_argument(phase)
      phase
    end

    def parse_command(parent)
#     puts "#parse_command"
      command = Ast::SourceCommand.new(parent, read)
      if peek.kind == :PIPE
        min_indent = tokenizer.indent + 1
        read
        command.source = readtext(min_indent)&.text
      else
        command.source = readline&.text
      end or unexpected_token_error peek, "command"
      command
    end

    def parse_if(parent)
#     puts "#parse_if"
      if_ = Ast::If.new(parent, peek)
      if_.if_thens = []
      loop do
        if_then = Ast::IfThen.new(if_, read)
        if_.if_thens << if_then
        if_then.expr = parse_expr(if_then)
        if_then.then_ = parse_block(if_then)
        break if peek.kind != :ELSIF
      end
      if peek.kind == :ELSE
        read
        if_.else_ = parse_block(if_)
      end
      readkind(:END)
      if_
    end

    def parse_case(parent)
      case_ = Ast::Case.new(parent, read)
      case_.const = parse_constant(case_)
      case_.whens = []
      while peek.kind == :WHEN
        when_ = Ast::When.new(case_, read)
        case_.whens << when_
        when_.values = parse_values(when_)
        when_.then_ = parse_block(when_)
      end
      !case_.whens.empty? or unexpected_token_error peek, "'when'"
      if peek.kind == :ELSE
        read
        case_.else_ = parse_block(case_)
      end
      readkind(:END)
      case_
    end

    # Parse an expression. It uses the shunter to compile the source into
    # reverse polish notation that is then converted into an Ast::Expr
    def parse_expr(parent)
#     puts "#parse_expr"
      stack = []
      shunt_exprs.each { |token| # Token may actually be an Expr but it quacks like a token in this context
        if token.is_a? Ast::SimpleExpr
          stack.push token
        elsif oper = OPERATORS[token.kind]
          case oper[:arity]
            when 1
              e = Ast::UnExpr.new(nil, token)
              e.attach(stack.pop)
              stack.push e
            when 2
              e = Ast::BinExpr.new(nil, token)
              r = stack.pop
              l = stack.pop
              e.attachs(l, r)
              stack.push e
          else
            raise InternalError
          end
        else
          stack.push token
        end
      }
      stack.first or unexpected_token_error read, "expression"
      parent.attach stack.first
    end

    # Parses list of words (cmd, env, user). Note: Called from the shunter to
    # generate simple expressions
    def parse_simple_expr # token should be equal to #peek
#     puts "parse_simple_expr"
      case peek.kind
        when :CMD, :ENV, :USER
          expr = Ast::RuntimeExpr.new(nil, read)
          parse_idents(expr)
        when :SCHEMA
          expr = Ast::ReferenceExpr.new(nil, read)
          Ast::Reference.new(expr, readkind(:IDENT))
        when :OBJECT
          expr = Ast::ReferenceExpr.new(nil, read)
          Ast::Reference.new(expr, readkind(:REF, :IDENT))
        when :RESOURCE
          expr = Ast::ReferenceExpr.new(nil, read)
          Ast::Reference.new(expr, readkind(:REF, :IDENT))
        when :VERSION
          expr = Ast::VersionExpr.new(nil, read)
          while VERSION_OPERATORS.include?(peek.kind)
            match = Ast::VersionMatch.new(expr, read)
            ver = Ast::Ver.new(match, readkind(:VER))
          end
          !expr.matches.empty? or unexpected_token_error peek, "version operator"
      else
        unexpected_token_error peek, "simple expression"
      end
      expr
    end

    def parse_values(parent)
      readwhile { parse_value? parent }
    end

    def parse_ruby(parent)
      not_implemented_error "#parse_ruby"
    end

    # Parse a list of files. Return array of File objects. Raise an error if
    # the array is empty and :check is true
    #
    def parse_files(parent, check: true)
#     puts "#parse_files"
      check_expected "files" do
        r = []
        while !@tokenizer.eof? && (token = peek) && token.kind == :FILE
          r << Ast::File.new(parent, read)
        end
        next nil if r.empty?
        r
      end
    end

    def parse_ident?(parent) = peek&.kind == :IDENT ? Ast::Ident.new(parent, read) : nil
    def parse_ident(parent) = Ast::Ident.new(parent, readkind(:IDENT))

    def parse_idents?(parent) = readwhile? { parse_ident? parent }
    def parse_idents(parent) = check_expected("identifier") { readwhile { parse_ident? parent } }

    def parse_refs(parent)
      readkinds(:IDENT, :REF).map { Ast::Reference.new(parent, _1) }
    end

    # Parse a space-separated list of values. Values are IDENT, REF, or a version match
    def parse_value?(parent)
      case peek.kind
        when :IDENT, :REF
          Ast::Reference.new(parent, read)
        when :VER # Default '==' operator
          ver = read
          oper = Token.new(ver.file, ver.lineno, ver.charno, "==", :EQEQ)
          value = Ast::VersionMatch.new(parent, oper)
          Ast::Ver.new(value, ver)
          value
        when *VERSION_OPERATORS
          value = Ast::VersionMatch.new(parent, read)
          Ast::Ver.new(value, readkind(:VER))
          value
      else
        nil
      end
    end

    def parse_constant(parent)
      Ast::Const.new(parent, readkind(*CONSTANTS))
    end

    #
    # S H U N T I N G
    #
    def shunt_exprs
#     puts "#shunt_exprs"
      stack = []
      output = []
      token_args = {} # Map from list operators 'env' and 'cmd' to array of arguments

      while token = peek
        case token.kind
          when :PAREN_BEGIN
            stack.push(read)
          when :PAREN_END
            read
            while op = stack.pop and op.kind != :PAREN_BEGIN
              output << op
            end
          when *CONSTANTS
            output << parse_simple_expr
          else
            oper = OPERATORS[token.kind] or break
            read
            while top = OPERATORS[stack.last&.kind]
              break if oper[:prior] > top[:prior]
              break if oper[:prior] == top[:prior] && oper[:assoc] == :right
              output << stack.pop
            end
            stack.push token
        end
      end

      output + stack.reverse
    end

    #
    # T O K E N I Z E R  I N T E R F A C E
    #

    # Functions from tokenizer with error handling
    # TODO: Check if **opts is actually used
    def peek(**opts) = @tokenizer.peek(**opts) or error(@tokenizer.error_token)
    def read(**opts) = @tokenizer.read(**opts) or error(@tokenizer.error_token)
    def readline(**opts) = @tokenizer.readline(**opts) or error(@tokenizer.error_token)
    def readtext(indent, **opts) = @tokenizer.readtext(indent, **opts) or error(@tokenizer.error_token)
    def readkind(*kinds, **opts) = readkind?(*kinds, **opts) or unexpected_token_error kinds
    def readkinds(*kinds, **opts) = [readkind(*kinds)] + readkinds?(kinds, **opts)

    # Return nil if empty
    def readwhile(&block) = (r = readwhile?(&block)).empty? ? nil : r

    # Functions from tokenizer that accepts a nil return. FIXME this sacrifices
    # run-time performance for code clarity
    def peek?(**opts) = @tokenizer.peek(**opts)
    def read?(**opts) = @tokenizer.read(**opts)
    def readline?(**opts) = @tokenizer.readline(**opts)
    def readtext?(indent, **opts) = @tokenizer.readtext(indent, **opts)

    def readkind?(*kinds, **opts)
      kinds.include? peek&.kind or return nil
      read
    end

    # Note: Returns an empty list if no token was found
    def readkinds?(*kinds, **opts)
      kinds = Array(kinds).flatten
      a = []
      while kinds.include? peek(**opts)&.kind
        a << read(**opts)
      end
      a
    end

    # Note: Returns an empty list if no token was found
    def readwhile?(&block)
      a = []
      r = yield
      while r
        a << r
        r = yield
      end
      a
    end

    #
    # E R R O R   H A N D L I N G
    #

    # :call-seq:
    #   unexpected_token_error(token = tokenizer.error_token || tokenizer.token, *words)
    #
    # Raise an error with the message format
    #
    #   Expected WORD, ..., or WORD, got WORD
    #
    # The error will be located at the given token (default tokenizer #error or
    # #token). Note that it does not check for an error, it only displays it
    #
    # Some prettyfication is done on words
    #
    def unexpected_token_error(*args)
      token = args.first.is_a?(Token) ? args.shift : tokenizer.error || tokenizer.peek_error || tokenizer.token or
          raise ArgumentError
      words = Array(*args).flatten.map! { |w| w.is_a?(Symbol) ? Token::TEXTS[w] : w }
      words = seq words
      source = token.respond_to?(:error) && token.error || token.text
      got = (source.empty? ? "" : ", got '#{source}'")
      message = "Expected #{words}#{got}"
      error token, message
    end

    def check_expected(words, &block)
      token = peek and r = yield(token) or unexpected_token_error token, words
      r
    end

    def not_implemented_error(*args)
      token = args.first.is_a?(Token) ? args.shift : tokenizer.error || tokenizer.peek_error || tokenizer.token
      token or raise ArgumentError
      method_name = args.shift
      message = "#{method_name} is not implemented"
      error token, message
    end

    #
    # U T I L I T I E S
    #

    # English language sequence of words. Eg 'a, b, or c'
    def seq(words)
      words.map!(&:to_s)
      case words.size
        when 1; words.first
        when 2; words.join(" or ")
        else words[0..-2].join(", ") + ", or " + words.last
      end
    end
  end
end


